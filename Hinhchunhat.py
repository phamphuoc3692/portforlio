chieu_dai = input("Nhập chiều dài hình chữ nhật: ")
chieu_rong = input("Nhập chiều rộng hình chữ nhật: ")
dien_tich = float(chieu_dai) * float(chieu_rong)
chu_vi = (float(chieu_dai) + float(chieu_rong)) * 2
print(f"Diện tích hình chữ nhật là: {dien_tich}")
print(f"Chu vi hình chữ nhật là: {chu_vi}")